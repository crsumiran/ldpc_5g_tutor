// Opt-in browser smoke. API interception sends every request to disposable data.
const assert = require("node:assert/strict");
const { chromium } = require(process.env.LDPC_PLAYWRIGHT_MODULE);

(async () => {
  const browser = await chromium.launch({ headless: true });
  const page = await browser.newPage({ viewport: { width: 1500, height: 1000 } });
  const errors = [];
  page.on("pageerror", error => errors.push(error.message));
  await page.route("**/api/**", async route => {
    const url = new URL(route.request().url());
    const response = await route.fetch({ url: "http://127.0.0.1:8021" + url.pathname + url.search });
    await route.fulfill({ response });
  });
  try {
    await page.goto("http://127.0.0.1:3000/?course=ldpc-5g");
    await page.getByRole("heading", { name: "Why do we need error correction?", exact: true }).waitFor();
    assert.equal(await page.locator('.ldpc-article').count(),1);
    assert.equal(await page.locator('.ldpc-article .notebook-cell').count(),0);
    assert.equal(await page.getByRole("button", { name: /^Run public tests/ }).count(), 0);
    await page.getByText("Show the explanation", { exact: true }).click();
    await page.getByText(/It could have been sent as 001/).waitFor();
    await page.getByRole("button", { name: "Next theory page →", exact: true }).click();
    await page.getByRole("heading", { name: "Extra bits make mistakes recoverable", exact: true }).waitFor();
    await page.getByText("Optional: explore the explanation visually",{exact:true}).click();
    await page.getByRole("button", { name: "Received bit 0, 1", exact: true }).click();
    await page.getByText(/more than one flip defeated this code/).waitFor();
    await page.getByRole("button", { name: "Next theory page →", exact: true }).click();
    await page.getByRole("heading", { name: "Parity rules, then the syndrome", exact: true }).waitFor();
    for (let i = 0; i < 2; i++) await page.getByRole("button", { name: "Next theory page →", exact: true }).click();
    assert.equal(await page.locator('.decode-scene').isVisible(),false);
    assert.match(await page.locator('.ldpc-article').innerText(),/All three combined scores are now/);
    assert.doesNotMatch(await page.locator('.ldpc-article').innerText(),/\[3,-1,-1\]/);
    await page.locator('.ldpc-article').screenshot({path:'/tmp/ldpc-blog-chapter5.png'});
    await page.getByText("Optional: explore the explanation visually",{exact:true}).click();
    await page.getByRole("heading", { name: "How can a rule help a weak guess?", exact: true }).waitFor();
    const scene = page.locator(".decode-scene");
    assert.match(await scene.innerText(), /Guess: 1/);
    assert.equal(await page.getByText("b1 radio clue", {exact:false}).isVisible(), false);
    await page.getByRole("button", {name:"Next step →",exact:true}).click();
    await page.getByText("0 XOR 1 XOR 0 = 1 → rule fails", {exact:true}).waitFor();
    await page.getByRole("button", {name:"Next step →",exact:true}).click();
    await page.getByLabel("First and last bits provide evidence to the rule, which sends advice to the middle bit").waitFor();
    await page.screenshot({path:"/tmp/ldpc-decoding-advice.png",fullPage:true});
    await page.getByRole("button", {name:"Next step →",exact:true}).click();
    const middle = page.locator(".decode-target");
    assert.match(await middle.innerText(), /Guess: 0/);
    assert.match(await middle.innerText(), /Radio clue: -0.2/);
    assert.match(await middle.innerText(), /Combined: \+2.8/);
    await page.getByRole("button", {name:"Next step →",exact:true}).click();
    await page.getByText("0 XOR 0 XOR 0 = 0 → rule passes", {exact:true}).waitFor();
    await page.getByText("What do +4, −0.2 and +3 mean? Show the optional maths",{exact:true}).click();
    assert.equal(await page.getByText("b1 radio clue", {exact:false}).isVisible(), true);
    await page.screenshot({path:"/tmp/ldpc-decoding-desktop.png",fullPage:true});
    await page.setViewportSize({width:390,height:844});
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth), false);
    await page.screenshot({path:"/tmp/ldpc-decoding-mobile.png",fullPage:true});
    await page.setViewportSize({width:1500,height:1000});
    await page.getByRole("button", { name: "Next theory page →", exact: true }).click();
    await page.getByRole("heading", { name: "From these ideas to 5G hardware", exact: true }).waitFor();
    await page.getByRole("button", { name: "Continue to assignments →", exact: true }).click();
    await page.getByRole("heading", { name: "GF(2): bits are not ordinary numbers", exact: true }).waitFor();
    const assignment=page.getByRole('article',{name:'Assignment explanation'});
    assert.match(await assignment.innerText(),/A parity rule checks/);
    assert.match(await assignment.innerText(),/A bit is a value that is either 0 or 1/);
    assert.doesNotMatch(await assignment.innerText(),/What changes and what stays fixed|Recap before coding/);
    await page.getByRole("button", { name: "Reveal worked results", exact: true }).click();
    await page.getByLabel("Worked fixture variant").selectOption("0");
    assert.match(await page.locator(".ldpc-visual").innerText(), /flip|Flip/);
    await page.getByRole("button", { name: /^Run public tests/ }).click();
    await page.getByText("3 public check(s) need attention", { exact: true }).waitFor({ timeout: 45000 });
    await page.getByText('Inputs, expected outputs and actual results',{exact:true}).waitFor();
    assert.match(await page.locator('.raw-output pre').innerText(),/INPUT:.*\nEXPECTED OUTPUT:/);
    assert.match(await page.locator('.raw-output pre').innerText(),/ACTUAL OUTPUT:.*NotImplementedError/);
    const content = page.locator(".cm-content");
    await content.click();
    await page.keyboard.press("Control+a");
    await page.keyboard.insertText("def gf2_dot(a, b):\n    return sum(int(x)*int(y) for x,y in zip(a,b)) % 2\n");
    await page.getByRole("button", { name: /^Submit checkpoint/ }).click();
    await page.getByText("Checkpoint passed", { exact: true }).waitFor({ timeout: 45000 });
    await page.getByRole("button", { name: "Read the theory behind this assignment →", exact: true }).click();
    await page.getByRole("heading", { name: "Parity rules, then the syndrome", exact: true }).waitFor();
    await page.getByRole("button", { name: "Discuss this theory with the guide ↗", exact: true }).click();
    await page.locator(".desktop-tutor").getByText(/not a tailored answer to your question/).waitFor({timeout:15000});
    await page.screenshot({ path: "/tmp/ldpc-theory-desktop.png", fullPage: true });
    await page.setViewportSize({ width: 390, height: 844 });
    await page.screenshot({ path: "/tmp/ldpc-theory-mobile.png", fullPage: true });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth), false);
    await page.setViewportSize({ width: 1500, height: 1000 });
    await page.reload();
    await page.getByRole("heading", { name: "Parity rules, then the syndrome", exact: true }).waitFor();
    await page.getByRole("button", { name: "Resume assignments →", exact: true }).click();
    // Restore opens the next available assignment; theory never changes grades.
    await page.getByRole("heading", { name: "Syndrome: which rules are broken?", exact: true }).waitFor();
    await page.locator(".desktop-rail").getByRole("button", { name: /GF\(2\): bits are not ordinary numbers/ }).click();
    assert.match(await page.locator(".cm-content").innerText(), /return sum/);
    const next = page.locator(".desktop-rail").getByRole("button", { name: /Syndrome: which rules are broken/ });
    assert.equal(await next.isDisabled(), false);
    await next.click();
    await page.getByRole("heading", { name: "Syndrome: which rules are broken?", exact: true }).waitFor();
    await page.locator(".desktop-tutor #tutor-question").fill("Why can zero syndrome still mean the wrong payload?");
    await page.getByRole("button", { name: "Ask guide ↗", exact: true }).click();
    await page.locator(".desktop-tutor").getByText(/no OpenRouter key configured; authored explanation/).last().waitFor({ timeout: 15000 });
    await page.screenshot({ path: "/tmp/ldpc-tutor-desktop.png", fullPage: true });
    await page.setViewportSize({ width: 390, height: 844 });
    await page.screenshot({ path: "/tmp/ldpc-tutor-mobile.png", fullPage: true });
    await page.setViewportSize({ width: 1500, height: 1000 });
    await page.goto("http://127.0.0.1:3000/?course=cache-lab");
    await page.getByRole("heading", { name: "Decode the Address", exact: true }).waitFor();
    assert.equal(errors.length,0,errors.join("\n"));
    console.log("Browser smoke passed: six theory pages, repetition errors, explanations, theory chat, reading restore, preserved code/progress, parity interaction, public tests/unlock, mobile layout, cache route.");
  } finally {
    await browser.close();
  }
})().catch(error => { console.error(error); process.exitCode=1; });
